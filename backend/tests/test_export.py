def test_export_requires_auth(harness, auth_headers):
    contract_id = harness.create_contract(auth_headers)["id"]
    response = harness.client.post(f"/contracts/{contract_id}/export", json={"format": "pdf"})
    assert_error(response, 401, "UNAUTHORIZED")


def test_the_filename_header_is_readable_cross_origin(harness, auth_headers):
    """The frontend runs on another origin and reads the filename from Content-Disposition."""
    contract_id = harness.create_contract(auth_headers)["id"]
    response = harness.client.post(
        f"/contracts/{contract_id}/export", json={"format": "pdf"},
        headers={**auth_headers, "Origin": "http://localhost:8080"},
    )
    assert response.headers["access-control-allow-origin"] == "http://localhost:8080"
    assert "content-disposition" in response.headers["access-control-expose-headers"].lower()
